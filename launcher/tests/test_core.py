"""Checks the launcher's non-UI logic.

Run from the launcher folder:  python -m pytest tests   (or: python tests/test_core.py)
"""

import json
import os
import shutil
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from core import ahk, buffwatch, macros, paths, procs, settings  # noqa: E402


def _tmp():
    return tempfile.mkdtemp(prefix="launcher-test-")


def test_paths_point_at_the_repo():
    assert os.path.isfile(paths.GENERATOR)
    assert os.path.isdir(paths.CONFIGS_DIR)
    assert os.path.isfile(paths.BUFFWATCH_SCRIPT)
    assert os.path.isfile(paths.BUFFWATCH_RUN_BAT)


def test_every_shipped_config_reads():
    configs = macros.list_configs()
    assert configs
    for c in configs:
        assert c.error is None, (c.path, c.error)
        assert c.macros, c.path
        with open(c.path, encoding="utf-8") as f:
            assert json.load(f)["$schema"] == "../ahkgen.schema.json"


def test_config_summary_and_status():
    d = _tmp()
    try:
        cfg_dir, gen_dir = os.path.join(d, "configs"), os.path.join(d, "generated")
        os.makedirs(cfg_dir)
        with open(os.path.join(cfg_dir, "saryn_spores.json"), "w") as f:
            json.dump({"settings": {"panic_hotkey": "F12"}, "macros": [
                {"name": "Spores", "hotkey": "F1", "steps": [{"tap": "1"}]},
                {"hotkey": "F2", "steps": [{"tap": "2"}]}]}, f)
        with open(os.path.join(cfg_dir, "broken.json"), "w") as f:
            f.write("{nope")
        broken, c = macros.list_configs(cfg_dir, gen_dir)
        assert broken.status() == macros.BROKEN
        assert c.title == "Saryn spores"
        assert c.macros == [("F1", "Spores", ""), ("F2", "F2", "")]
        assert c.panic_hotkey == "F12"
        assert c.status() == macros.MISSING
        os.makedirs(gen_dir)
        with open(c.script, "w") as f:
            f.write("; generated")
        assert c.status() == macros.READY
        later = time.time() + 5
        os.utime(c.path, (later, later))
        assert c.status() == macros.STALE
    finally:
        shutil.rmtree(d)


def test_create_config():
    d = _tmp()
    try:
        p = macros.create_config("  Saryn: Spores!! ", d)
        assert os.path.basename(p) == "saryn_spores.json"
        c = macros.Config(p, d)
        assert c.error is None and c.macros
        try:
            macros.create_config("saryn spores", d)
            assert False, "should refuse to overwrite"
        except FileExistsError:
            pass
        try:
            macros.create_config("!!!", d)
            assert False, "should refuse an empty name"
        except ValueError:
            pass
    finally:
        shutil.rmtree(d)


def test_generate_matches_running_ahkgen_by_hand():
    if not macros.powershell():
        print("skipped: no PowerShell")
        return
    d = _tmp()
    try:
        src = macros.list_configs()[0]
        c = macros.Config(src.path, d)
        ok, out = macros.generate(c)
        assert ok, out
        with open(c.script, encoding="utf-8-sig") as f:
            text = f.read()
        assert "GENERATED by ahkgen.ps1" in text
        assert c.status() == macros.READY
    finally:
        shutil.rmtree(d)


def test_ahk_command_lines():
    assert procs.is_ahk_exe("AutoHotkeyU64.exe")
    assert procs.is_ahk_exe("AutoHotkey.exe")
    assert procs.is_ahk_exe("autohotkey64.exe")
    assert not procs.is_ahk_exe("AutoHotkeyUX.exe")
    assert not procs.is_ahk_exe("python.exe")
    assert procs.ahk_script_of(["C:\\AHK\\AutoHotkey.exe", "/restart", "C:\\m\\x.ahk"]) == "C:\\m\\x.ahk"
    assert procs.ahk_script_of(["AutoHotkey.exe"]) is None


def test_buffwatch_command_lines():
    assert procs.is_buffwatch("pythonw.exe", ["pythonw.exe", "C:\\wf\\buff_watch\\buffwatch.pyw"])
    assert procs.is_buffwatch("pythonw.exe", ["pythonw.exe", "buffwatch.pyw", "--image", "x"])
    assert procs.is_buffwatch("BuffWatch.exe", ["BuffWatch.exe"])
    assert not procs.is_buffwatch("python.exe", ["python.exe", "launcher.pyw"])
    assert procs.BUFFWATCH_MAIN_TITLE.match("BuffWatch")
    assert procs.BUFFWATCH_MAIN_TITLE.match("BuffWatch - 3 new icons")
    assert not procs.BUFFWATCH_MAIN_TITLE.match("BuffWatch - teach an icon")


def test_buffwatch_data_dirs():
    assert buffwatch.data_dir(buffwatch.SOURCE) == os.path.join(paths.BUFFWATCH_DIR, "data")
    assert buffwatch.data_dir(buffwatch.EXE) == os.path.join(
        paths.BUFFWATCH_DIR, "dist", "BuffWatch", "data")
    assert buffwatch.resolve_mode("exe") == "exe"
    assert buffwatch.resolve_mode("auto") in ("source", "exe")


def test_find_ahk_v1():
    d = _tmp()
    try:
        assert ahk.find_v1([d]) == ""
        v1 = os.path.join(d, "v1.1.37.02")
        os.makedirs(v1)
        open(os.path.join(v1, "AutoHotkeyU64.exe"), "w").close()
        assert ahk.find_v1([d]) == os.path.join(v1, "AutoHotkeyU64.exe")
        open(os.path.join(d, "AutoHotkey.exe"), "w").close()
        assert ahk.find_v1([d]) == os.path.join(d, "AutoHotkey.exe")
    finally:
        shutil.rmtree(d)


def test_settings_roundtrip():
    d = _tmp()
    try:
        p = os.path.join(d, "settings.json")
        s = settings.load(p)
        assert s["buffwatch_mode"] == "auto"
        s["ahk_exe"] = "C:\\x.exe"
        settings.save(s, p)
        assert settings.load(p)["ahk_exe"] == "C:\\x.exe"
        with open(p, "w") as f:
            f.write("garbage")
        assert settings.load(p)["page"] == "macros"
    finally:
        shutil.rmtree(d)


def test_uptime_format():
    assert procs.format_uptime(5) == "5s"
    assert procs.format_uptime(125) == "2m 05s"
    assert procs.format_uptime(3 * 3600 + 7 * 60) == "3h 07m"


